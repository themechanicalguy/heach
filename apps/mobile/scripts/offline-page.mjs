// Writes www/offline.html: the page the apps show when the web app cannot be reached (MA-05).
// Its text comes from the i18n catalogues, so it is generated, not written by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';

const LOCALES = ['or', 'en', 'hi'];
const catalogue = (locale) =>
  JSON.parse(
    readFileSync(
      fileURLToPath(new URL(`../../../packages/i18n/src/messages/${locale}.json`, import.meta.url)),
      'utf8',
    ),
  );

const escape = (text) =>
  text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');

/** One block per language; the script below shows the phone's. */
export function offlinePage(catalogues) {
  const blocks = LOCALES.map((locale) => {
    const { app, offline, state } = catalogues[locale];
    return `    <section lang="${locale}" hidden>
      <h1>${escape(app.name)}</h1>
      <p data-why="offline">${escape(offline.noConnection)}</p>
      <p data-why="server" hidden>${escape(state.error)}</p>
      <button type="button">${escape(state.retry)}</button>
    </section>`;
  }).join('\n');
  return `<!doctype html>
<!-- Generated by scripts/offline-page.mjs from packages/i18n. Do not edit. -->
<html>
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>HEACH</title>
    <style>
      body { margin: 0; min-height: 100vh; display: grid; place-items: center;
        font-family: system-ui, sans-serif; background: #f8f6fb; color: #241a38; }
      section { padding: 24px; max-width: 28rem; text-align: center; }
      p { font-size: 1.125rem; line-height: 1.5; }
      button { min-height: 48px; padding: 0 24px; border: 0; border-radius: 24px;
        font: inherit; font-weight: 600; background: #6b4fa3; color: #ffffff; }
    </style>
  </head>
  <body>
${blocks}
    <script>
      // The phone's language if HEACH has it, else Odia. The app passes the page to retry
      // and says when the server answered with a fault instead of being out of reach.
      var asked = new URLSearchParams(location.search);
      var phone = /^(or|en|hi)/.exec(navigator.language || '');
      var locale = phone ? phone[1] : 'or';
      document.documentElement.lang = locale;
      var block = document.querySelector('section[lang="' + locale + '"]');
      block.hidden = false;
      if (asked.get('why') === 'server') {
        block.querySelector('[data-why="offline"]').hidden = true;
        block.querySelector('[data-why="server"]').hidden = false;
      }
      // The launch screen waits for a page to say it is ready (MA-09); this one is. Capacitor
      // gives its script only to pages from the server, so this page posts the message itself.
      if (window.androidBridge) {
        androidBridge.postMessage(
          JSON.stringify({ callbackId: '-1', pluginId: 'SplashScreen', methodName: 'hide', options: {} }),
        );
      }
      block.querySelector('button').addEventListener('click', function () {
        var to = asked.get('to') || '';
        // Only ever a web address: this page can reach the app's bridge.
        if (to.indexOf('https://') === 0 || to.indexOf('http://') === 0) location.replace(to);
      });
    </script>
  </body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalogues = Object.fromEntries(LOCALES.map((locale) => [locale, catalogue(locale)]));
  writeFileSync(new URL('../www/offline.html', import.meta.url), offlinePage(catalogues));
}
