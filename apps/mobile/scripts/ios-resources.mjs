// Writes the iOS app's generated resources (ADR 0016):
// - <locale>.lproj/InfoPlist.strings: the camera permission text from the i18n catalogues (MA-06);
// - each app's icon and brand colour, the same care cross on the same colours as the Android apps.
import { Buffer } from 'node:buffer';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';
import { crc32, deflateSync } from 'node:zlib';

const LOCALES = ['or', 'en', 'hi'];
const APP_FOLDER = new URL('../ios/App/App/', import.meta.url);

/** Design tokens "primary" and "text" (packages/ui/src/tokens.ts), as in the Android apps. */
export const BRANDS = { patient: [0x6b, 0x4f, 0xa3], provider: [0x24, 0x1a, 0x38] };

const catalogue = (locale) =>
  JSON.parse(
    readFileSync(
      fileURLToPath(new URL(`../../../packages/i18n/src/messages/${locale}.json`, import.meta.url)),
      'utf8',
    ),
  );

const quoted = (text) => `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;

/** The strings iOS shows for the app itself, in one language. */
export function infoPlistStrings(messages) {
  return `/* Generated by scripts/ios-resources.mjs from packages/i18n. Do not edit. */
"NSCameraUsageDescription" = ${quoted(messages.app.cameraPurpose)};
`;
}

/**
 * Whether a point of a square icon is on the cross. The Android icon draws it on a 108-unit
 * canvas of which the middle 72 units show; the iPhone icon shows that same middle part.
 */
function onCross(x, y, size) {
  const u = 18 + (x / size) * 72;
  const v = 18 + (y / size) * 72;
  const vertical = u >= 44 && u < 64 && v >= 32 && v < 76;
  const horizontal = u >= 32 && u < 76 && v >= 44 && v < 64;
  return vertical || horizontal;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data]);
  const check = Buffer.alloc(4);
  check.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, check]);
}

/** An opaque RGB PNG: the App Store refuses icons with transparency. */
export function iconPng(size, brand) {
  const rows = [];
  for (let y = 0; y < size; y += 1) {
    const row = Buffer.alloc(1 + size * 3);
    for (let x = 0; x < size; x += 1) {
      const colour = onCross(x, y, size) ? [255, 255, 255] : brand;
      row.set(colour, 1 + x * 3);
    }
    rows.push(row);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header.set([8, 2, 0, 0, 0], 8);
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  const pixels = chunk('IDAT', deflateSync(Buffer.concat(rows)));
  return Buffer.concat([signature, chunk('IHDR', header), pixels, chunk('IEND', Buffer.alloc(0))]);
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const info = { author: 'xcode', version: 1 };

/** The asset catalogue's Contents.json for an icon and for a colour. */
export function iconContents() {
  return json({
    images: [{ filename: 'icon.png', idiom: 'universal', platform: 'ios', size: '1024x1024' }],
    info,
  });
}

export function colourContents([red, green, blue]) {
  const component = (value) => `0x${value.toString(16).padStart(2, '0').toUpperCase()}`;
  const components = { red: component(red), green: component(green), blue: component(blue) };
  return json({
    colors: [
      {
        color: { 'color-space': 'srgb', components: { ...components, alpha: '1.000' } },
        idiom: 'universal',
      },
    ],
    info,
  });
}

function write(path, content) {
  const target = new URL(path, APP_FOLDER);
  mkdirSync(new URL('.', target), { recursive: true });
  writeFileSync(target, content);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const locale of LOCALES) {
    write(`${locale}.lproj/InfoPlist.strings`, infoPlistStrings(catalogue(locale)));
  }
  for (const [audience, brand] of Object.entries(BRANDS)) {
    write(`Assets.xcassets/AppIcon-${audience}.appiconset/icon.png`, iconPng(1024, brand));
    write(`Assets.xcassets/AppIcon-${audience}.appiconset/Contents.json`, iconContents());
    write(`Assets.xcassets/Brand-${audience}.colorset/Contents.json`, colourContents(brand));
  }
}
