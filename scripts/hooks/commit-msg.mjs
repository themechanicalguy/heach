// commit-msg: Conventional Commits, e.g. "feat(api): add readiness checks".
import { readFileSync } from 'node:fs';
import process from 'node:process';
import { fail } from './run.mjs';

const TYPES = [
  'feat',
  'fix',
  'docs',
  'chore',
  'refactor',
  'test',
  'ci',
  'build',
  'perf',
  'style',
  'revert',
];
const PATTERN = new RegExp(`^(${TYPES.join('|')})(\\([a-z0-9-]+\\))?!?: \\S.{0,99}$`);

const file = process.argv[2];
if (!file) fail('commit-msg hook called without a message file');
const subject = readFileSync(file, 'utf8').split('\n')[0] ?? '';

// Merge and revert commits generated by git keep their default subjects.
if (!/^(Merge|Revert) /.test(subject) && !PATTERN.test(subject)) {
  fail(
    `Commit message must follow Conventional Commits:\n  <type>(<scope>): <summary, max 100 chars>\n` +
      `  types: ${TYPES.join(', ')}\n  got: "${subject}"`,
  );
}
